#!/usr/bin/env python3
"""Generates src/features/terminal/errorPhrases.generated.ts: the translated error messages of the
C library and bash, so error lines are recognised when the system speaks another language.

coreutils is left out on purpose: its messages ("cannot access %s") keep only a short, generic
fragment once the file name is removed ("nicht möglich" in German), and its lines already end with
the C library's message ("No such file or directory"), which is recognised.

Usage: scripts/import-error-phrases.py PO_DIR [PO_DIR...]

Each PO_DIR holds catalogues named <package>-<language>.po (package: libc or bash). Use
both upstream translations (https://translationproject.org/latest/<package>/<language>.po, what
Fedora and Arch ship) and Ubuntu's (msgunfmt of the .mo files in language-pack-<language>-base),
because their wording differs ("No existe el fichero..." upstream, "No existe el archivo..." on Ubuntu).
"""
import json
import re
import sys
from pathlib import Path

# The messages that mean something failed, by package.
MESSAGES = {
    "libc": [
        "No such file or directory",
        "Permission denied",
        "Operation not permitted",
        "Segmentation fault",
        "Connection refused",
        "No space left on device",
        "Read-only file system",
    ],
    "bash": ["command not found"],
}

OUT = Path(__file__).resolve().parent.parent / "src/features/terminal/errorPhrases.generated.ts"


ESCAPES = {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}


def unquote(text: str) -> str:
    """A .po string literal without its quotes; C escapes other than \\n, \\t, \\" and \\\\ are kept as is."""
    if not (text.startswith('"') and text.endswith('"')):
        return text
    return re.sub(r"\\(.)", lambda m: ESCAPES.get(m.group(1), m.group(0)), text[1:-1])


def entries(path: Path):
    """(msgid, msgstr) of the translated, non-fuzzy entries of a .po file."""
    msgid, msgstr, fuzzy, field = None, None, False, None
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines() + [""]:
        line = raw.strip()
        if not line:
            if msgid and msgstr and not fuzzy:
                yield msgid, msgstr
            msgid, msgstr, fuzzy, field = None, None, False, None
        elif line.startswith("#,"):
            fuzzy = "fuzzy" in line
        elif line.startswith("#"):
            continue
        elif line.startswith("msgid "):
            msgid, field = unquote(line[6:]), "id"
        elif line.startswith("msgstr "):
            msgstr, field = unquote(line[7:]), "str"
        elif line.startswith('"') and field == "id":
            msgid += unquote(line)
        elif line.startswith('"') and field == "str":
            msgstr += unquote(line)
        else:
            field = None


# Format directives and quotes split a message; an apostrophe between letters (French "d'accéder")
# belongs to the word.
PLACEHOLDER = re.compile(
    r"%(\d+\$)?[-#0 +']*\d*(\.\d+)?[a-zA-Z]|[`\"‘“”«»「」『』]|(?<![^\W\d_])['’]|['’](?![^\W\d_])"
)


def phrase(translation: str) -> str | None:
    """The longest fixed part of a message, lower-cased; None when it is too short to be telling."""
    parts = [p.strip(" :.,;!¡¿?()") for p in PLACEHOLDER.split(translation) if p]
    best = max(parts, key=len, default="").lower()
    wide = any(ord(c) > 0x2E7F for c in best)  # CJK and the like: few characters say a lot
    return best if len(best) >= (4 if wide else 8) else None


def main(dirs: list[str]) -> None:
    phrases: set[str] = set()
    for package, wanted in MESSAGES.items():
        phrases.update(p for p in (phrase(m) for m in wanted) if p)
        for directory in dirs:
            for path in sorted(Path(directory).glob(f"{package}-*.po")):
                for msgid, msgstr in entries(path):
                    if msgid in wanted and (found := phrase(msgstr)):
                        phrases.add(found)
    body = "\n".join(f"  {json.dumps(p, ensure_ascii=False)}," for p in sorted(phrases))
    OUT.write_text(
        "// Generated by scripts/import-error-phrases.py from the translations of the C library\n"
        "// and bash (Translation Project and Ubuntu language packs). Do not edit.\n\n"
        "/** Lower-case fixed parts of system error messages, in English and the translated wordings. */\n"
        f"export const SYSTEM_ERROR_PHRASES: string[] = [\n{body}\n];\n",
        encoding="utf-8",
    )
    print(f"{len(phrases)} phrases written to {OUT}")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    main(sys.argv[1:])
