def svg_uri(path: Path) -> str:
    return "data:image/svg+xml;utf8," + urllib.parse.quote(path.read_text(encoding="utf-8").strip(), safe=" =:/;,'\"")


def main(package: str) -> None:
    root = Path(package)
    theme = json.loads((root / "dist/material-icons.json").read_text(encoding="utf-8"))
    light = theme.get("light", {})

    def pick(source: dict, keys: list[str]) -> dict:
        return {k: source[k] for k in keys if k in source}

    maps = {
        "extensions": pick(theme["fileExtensions"], EXTENSIONS),
        "names": pick(theme["fileNames"], FILE_NAMES),
        "folders": pick(theme["folderNames"], FOLDER_NAMES),
        "openFolders": pick(theme["folderNamesExpanded"], FOLDER_NAMES),
    }
    light_maps = {
        "extensions": pick(light.get("fileExtensions", {}), EXTENSIONS),
        "names": pick(light.get("fileNames", {}), FILE_NAMES),
        "folders": pick(light.get("folderNames", {}), FOLDER_NAMES),
        "openFolders": pick(light.get("folderNamesExpanded", {}), FOLDER_NAMES),
    }
    # Extensions the theme gives through VS Code's language ids (e.g. ts -> typescript).
    for ext in EXTENSIONS:
        if ext not in maps["extensions"] and ext in theme.get("languageIds", {}):
            maps["extensions"][ext] = theme["languageIds"][ext]
    used = {theme["file"], theme["folder"], theme["folderExpanded"]}
    for group in (maps, light_maps):
        for m in group.values():
            used.update(m.values())
    icons = {}
    for name in sorted(used):
        definition = theme["iconDefinitions"].get(name)
        if not definition:
            continue
        icons[name] = svg_uri((root / "dist" / definition["iconPath"]).resolve())

    out = [
        "// Generated by scripts/import-material-icons.py from the Material Icon Theme for VS Code",
        f"// {json.loads((root / 'package.json').read_text())['version']} (Philipp Kief, MIT): only the icons listed in the script. Do not edit.",
        "",
        "/** Icon name -> its SVG as a data URI. */",
        f"export const MATERIAL_ICONS: Record<string, string> = {json.dumps(icons, ensure_ascii=False)};",
        "",
        f"export const MATERIAL_FILE = {json.dumps(theme['file'])};",
        f"export const MATERIAL_FOLDER = {json.dumps(theme['folder'])};",
        f"export const MATERIAL_OPEN_FOLDER = {json.dumps(theme['folderExpanded'])};",
        "",
        "/** File extension (without the dot, lower case; may be compound such as d.ts), file name and folder name -> icon. */",
        f"export const MATERIAL_MAPS = {json.dumps(maps, ensure_ascii=False, sort_keys=True)};",
        "",
        "/** The same for light colour schemes, where an icon has a light variant. */",
        f"export const MATERIAL_LIGHT_MAPS = {json.dumps(light_maps, ensure_ascii=False, sort_keys=True)};",
        "",
    ]
    OUT.write_text("\n".join(out), encoding="utf-8")
    print(f"{len(icons)} icons -> {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
