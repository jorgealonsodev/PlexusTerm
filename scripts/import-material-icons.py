#!/usr/bin/env python3
"""Generates src/features/files/materialIcons.generated.ts from the Material Icon Theme for VS Code
(Philipp Kief, MIT), for the "Material" file icon pack: the icons of the file extensions, file
names and folder names below, as SVG data URIs, with their light-scheme variants.

Usage: scripts/import-material-icons.py MATERIAL_ICON_THEME_PACKAGE_DIR

Take the package from npm (`npm pack material-icon-theme`, then unpack it): the directory holds
dist/material-icons.json and icons/. See THIRD_PARTY_NOTICES.md.
"""
