#!/usr/bin/env python3
"""Generates src/features/files/setiIcons.generated.ts from VS Code's Seti file icon theme, the
default "Seti (Visual Studio Code)" theme, so the DEV mode file lists show the same icons.

Usage: scripts/import-seti-icons.py VS_SETI_ICON_THEME_JSON

Take the JSON and the font from the same VS Code release:
  https://raw.githubusercontent.com/microsoft/vscode/<tag>/extensions/theme-seti/icons/vs-seti-icon-theme.json
  https://raw.githubusercontent.com/microsoft/vscode/<tag>/extensions/theme-seti/icons/seti.woff  -> src/assets/seti.woff
The font and its icons are Seti UI's (MIT, Jesse Weed); see THIRD_PARTY_NOTICES.md.
"""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "src/features/files/setiIcons.generated.ts"


def char(code: str) -> str:
    """`\\E055` -> the character U+E055."""
    return chr(int(code.lstrip("\\"), 16))


def main(path: str) -> None:
    theme = json.loads(Path(path).read_text(encoding="utf-8"))
    used = set()
    maps = {}
    for scope, source in (("dark", theme), ("light", theme["light"])):
        maps[scope] = {
            "file": source["file"],
            "fileNames": source.get("fileNames", {}),
            "fileExtensions": source.get("fileExtensions", {}),
            "languageIds": source.get("languageIds", {}),
        }
        used.add(source["file"])
        for key in ("fileNames", "fileExtensions", "languageIds"):
            used.update(maps[scope][key].values())
    icons = {
        name: [char(d["fontCharacter"]), d.get("fontColor", "")]
        for name, d in sorted(theme["iconDefinitions"].items())
        if name in used
    }
    dump = lambda value: json.dumps(value, ensure_ascii=False, sort_keys=True)
    OUT.write_text(
        "// Generated by scripts/import-seti-icons.py from VS Code's Seti file icon theme\n"
        "// (vs-seti-icon-theme.json; icons by Seti UI, MIT). Do not edit.\n\n"
        "/** Icon name -> [the glyph in the Seti font, its colour]. */\n"
        f"export const SETI_ICONS: Record<string, [string, string]> = {dump(icons)};\n\n"
        "export interface SetiMap {\n"
        "  file: string;\n"
        "  fileNames: Record<string, string>;\n"
        "  fileExtensions: Record<string, string>;\n"
        "  languageIds: Record<string, string>;\n"
        "}\n\n"
        "/** Which icon each file name, extension and language gets, for dark and light schemes. */\n"
        f"export const SETI_DARK: SetiMap = {dump(maps['dark'])};\n\n"
        f"export const SETI_LIGHT: SetiMap = {dump(maps['light'])};\n",
        encoding="utf-8",
    )
    print(f"{len(icons)} icons written to {OUT}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
