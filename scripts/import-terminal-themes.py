# Windows Terminal key -> xterm.js ITheme key.
KEYS = {
    "background": "background",
    "foreground": "foreground",
    "cursorColor": "cursor",
    "selectionBackground": "selectionBackground",
    "black": "black",
    "red": "red",
    "green": "green",
    "yellow": "yellow",
    "blue": "blue",
    "purple": "magenta",
    "cyan": "cyan",
    "white": "white",
    "brightBlack": "brightBlack",
    "brightRed": "brightRed",
    "brightGreen": "brightGreen",
    "brightYellow": "brightYellow",
    "brightBlue": "brightBlue",
    "brightPurple": "brightMagenta",
    "brightCyan": "brightCyan",
    "brightWhite": "brightWhite",
}

REQUIRED = [k for k in KEYS if k not in ("cursorColor", "selectionBackground")]


def luminance(hex_color: str) -> float:
    r, g, b = (int(hex_color[i : i + 2], 16) / 255 for i in (1, 3, 5))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    source, commit = Path(sys.argv[1]), sys.argv[2]
    out = [
        "// Generated by scripts/import-terminal-themes.py; do not edit by hand.",
        f"// Palettes from iTerm2-Color-Schemes (MIT), commit {commit}; see THIRD_PARTY_NOTICES.md.",
        'import type { TerminalThemeEntry } from "./themes";',
        "",
        "export const IMPORTED_THEMES: TerminalThemeEntry[] = [",
    ]
    ids = set()
    for theme_id, name, file in SCHEMES:
        assert theme_id not in ids, theme_id
        ids.add(theme_id)
        data = json.loads((source / "windowsterminal" / f"{file}.json").read_text())
        missing = [k for k in REQUIRED if k not in data]
        assert not missing, f"{file}: missing {missing}"
        theme = {KEYS[k]: data[k].lower() for k in KEYS if k in data}
        theme.setdefault("cursor", theme["foreground"])
        theme["cursorAccent"] = theme["background"]
        # Windows Terminal blends the selection over the text; xterm.js needs the alpha.
        if "selectionBackground" in theme:
            theme["selectionBackground"] += "80"
        dark = luminance(theme["background"]) < 0.5
        out.append(f"  {{ id: {json.dumps(theme_id)}, name: {json.dumps(name, ensure_ascii=False)}, dark: {str(dark).lower()}, theme: {{")
        for key, value in theme.items():
            out.append(f"    {key}: {json.dumps(value)},")
        out.append("  } },")
    out.append("];")
    target = Path(__file__).resolve().parent.parent / "src/features/terminal/themes.generated.ts"
    target.write_text("\n".join(out) + "\n")
    print(f"{len(SCHEMES)} themes written to {target}")


if __name__ == "__main__":
    main()
